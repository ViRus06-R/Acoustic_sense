/**
 * Regenerates the Mosquitto password and ACL files from the node credentials in the database.
 *   npm run broker:sync-users            -> writes mosquitto/passwd and mosquitto/acl
 * Then reload Mosquitto (e.g. `kill -HUP <pid>` or restart the service).
 *
 * Node passwords are stored only as Mosquitto-compatible $7$ hashes, so they are copied as-is.
 * Two service accounts are added: the backend (read all) and the simulator (dev credential).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Pool } from "pg";
import { hashMqttPassword } from "../lib/server/nodes";

const out = path.join(process.cwd(), "mosquitto");
const prefix = process.env.TOPIC_PREFIX ?? "acousticsense";

async function main() {
  const pool = new Pool({ connectionString: process.env.DATABASE_URL ?? "postgres://postgres:postgres@127.0.0.1:5432/postgres", max: 1 });
  const nodes = (
    await pool.query<{ id: string; slug: string; mqtt_password_hash: string | null }>(
      "SELECT n.id, s.slug, n.mqtt_password_hash FROM nodes n JOIN sites s ON s.id = n.site_id WHERE n.decommissioned_at IS NULL ORDER BY n.id",
    )
  ).rows;
  await pool.end();

  const backendUser = process.env.MQTT_USERNAME || "acoustic-backend";
  const backendPass = process.env.MQTT_PASSWORD || "dev-backend-password";
  const simUser = process.env.SIM_MQTT_USERNAME || "simulator";
  const simPass = process.env.SIM_MQTT_PASSWORD || "dev-simulator-password";

  const passwd: string[] = [`${backendUser}:${await hashMqttPassword(backendPass)}`, `${simUser}:${await hashMqttPassword(simPass)}`];
  const acl: string[] = [
    "# Generated by scripts/sync-broker-users.ts - do not edit by hand",
    `user ${backendUser}`,
    `topic read ${prefix}/#`,
    "",
    "# Development simulator (publishes on behalf of all nodes)",
    `user ${simUser}`,
    `topic write ${prefix}/#`,
    "",
  ];
  let skipped = 0;
  for (const n of nodes) {
    if (!n.mqtt_password_hash) {
      skipped++;
      continue;
    }
    passwd.push(`${n.id}:${n.mqtt_password_hash}`);
    acl.push(`user ${n.id}`, `topic write ${prefix}/${n.slug}/${n.id}/alert`, `topic write ${prefix}/${n.slug}/${n.id}/telemetry`, `topic read ${prefix}/${n.slug}/${n.id}/config`, "");
  }
  mkdirSync(out, { recursive: true });
  writeFileSync(path.join(out, "passwd"), passwd.join("\n") + "\n", { mode: 0o600 });
  writeFileSync(path.join(out, "acl"), acl.join("\n") + "\n");
  console.log(`[sync-broker-users] wrote ${passwd.length} users to mosquitto/passwd and ACLs to mosquitto/acl (${skipped} node(s) without credentials skipped)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
